#!/usr/bin/env bash
# One-command install / update of MediFlow on a fresh Ubuntu server (22.04 or 24.04, x86 or ARM).
#
#   curl -fsSL https://raw.githubusercontent.com/MediFlow-io/mediflow-platform/main/deploy/install.sh | bash
#
# Run it again at any time to update to the latest main. It:
#   1. installs Docker if needed,
#   2. clones (or updates) the repository into ~/mediflow-platform,
#   3. opens ports 8080-8082 in the server's own firewall,
#   4. creates deploy/.env with fresh secrets on the first run (kept on later runs),
#   5. builds and starts every service, and waits until they are healthy,
#   6. on the first run, gives the demo accounts random passwords and prints them.
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/MediFlow-io/mediflow-platform.git}"
BRANCH="${BRANCH:-main}"
DIR="${DIR:-$HOME/mediflow-platform}"
PORTS=(8080 8081 8082)

say() { printf '\n\033[1;32m==> %s\033[0m\n' "$*"; }
rand() { openssl rand -hex "${1:-24}"; }

# ---------------------------------------------------------------- 1. Docker
if ! command -v docker >/dev/null 2>&1; then
  say "Installing Docker"
  curl -fsSL https://get.docker.com | sudo sh
  sudo usermod -aG docker "$USER"
fi
DOCKER="docker"
docker info >/dev/null 2>&1 || DOCKER="sudo docker"   # group membership applies from the next login

# A little swap stops builds from running out of memory on small servers.
if [ "$(swapon --show | wc -l)" -eq 0 ] && [ "$(free -m | awk '/Mem:/ {print $2}')" -lt 8000 ]; then
  say "Adding 2 GB of swap"
  sudo fallocate -l 2G /swapfile && sudo chmod 600 /swapfile && sudo mkswap /swapfile >/dev/null && sudo swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' | sudo tee -a /etc/fstab >/dev/null
fi

# ---------------------------------------------------------------- 2. Code
command -v git >/dev/null 2>&1 || { sudo apt-get update -qq && sudo apt-get install -y -qq git; }
if [ "${SKIP_UPDATE:-0}" = 1 ]; then
  say "Using the code already in $DIR"      # CI: test the checked-out commit
elif [ -d "$DIR/.git" ]; then
  say "Updating $DIR to the latest $BRANCH"
  git -C "$DIR" fetch --quiet origin "$BRANCH" && git -C "$DIR" checkout --quiet "$BRANCH" && git -C "$DIR" reset --quiet --hard "origin/$BRANCH"
else
  say "Downloading MediFlow into $DIR"
  git clone --quiet --branch "$BRANCH" "$REPO_URL" "$DIR"
fi
cd "$DIR"

# ---------------------------------------------------------------- 3. Firewall on the server itself
# Oracle Cloud's Ubuntu images block everything but SSH with iptables; other clouds use ufw or nothing.
say "Opening ports ${PORTS[*]}"
for port in "${PORTS[@]}"; do
  reject=$(sudo iptables -L INPUT -n --line-numbers 2>/dev/null | awk '/REJECT/ {print $1; exit}')
  if [ -n "$reject" ]; then   # insert just before the catch-all REJECT rule
    sudo iptables -C INPUT -p tcp --dport "$port" -j ACCEPT 2>/dev/null || sudo iptables -I INPUT "$reject" -p tcp --dport "$port" -j ACCEPT
  fi
  if command -v ufw >/dev/null 2>&1 && sudo ufw status | grep -q "Status: active"; then sudo ufw allow "$port/tcp" >/dev/null; fi
done
if command -v netfilter-persistent >/dev/null 2>&1; then sudo netfilter-persistent save >/dev/null 2>&1 || true; fi

# ---------------------------------------------------------------- 4. Secrets (first run only)
ENV_FILE=deploy/.env
if [ ! -f "$ENV_FILE" ]; then
  say "Creating $ENV_FILE with new secrets"
  PUBLIC_HOST="${PUBLIC_HOST:-$(curl -fsS --max-time 5 https://api.ipify.org || hostname -I | awk '{print $1}')}"
  KEY_DIR=$(mktemp -d)
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$KEY_DIR/private.pem" 2>/dev/null
  openssl rsa -in "$KEY_DIR/private.pem" -pubout -out "$KEY_DIR/public.pem" 2>/dev/null
  one_line() { awk '{printf "%s\\n", $0}' "$1"; }
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/install.sh on $(date -u +%Y-%m-%d). Keep it secret; it is not in git.
PUBLIC_HOST=$PUBLIC_HOST
PUBLIC_SCHEME=http
POSTGRES_PASSWORD=$(rand)
DJANGO_SECRET_KEY=$(rand 32)
AI_SERVICE_TOKEN=$(rand)
ADMIN_APP_KEY=base64:$(openssl rand -base64 32)
JWT_PRIVATE_KEY='$(one_line "$KEY_DIR/private.pem")'
JWT_PUBLIC_KEY='$(one_line "$KEY_DIR/public.pem")'
# Demo departments and accounts (their passwords are replaced with random ones below).
SEED_DEMO=true
TIME_ZONE=Africa/Lagos
CLINIC_HOURS=08:00-16:00
CLINIC_DAYS=Mon-Fri
# Recommended once staff have phones set up: MFA_REQUIRED_ROLES=admin,doctor,nurse
MFA_REQUIRED_ROLES=
EOF
  rm -rf "$KEY_DIR"
  FIRST_RUN=1
else
  say "Keeping the existing $ENV_FILE"
  FIRST_RUN=0
fi
PUBLIC_HOST=$(grep '^PUBLIC_HOST=' "$ENV_FILE" | cut -d= -f2)

# ---------------------------------------------------------------- 5. Build and start
COMPOSE="$DOCKER compose -f docker-compose.yml -f deploy/docker-compose.prod.yml --env-file $ENV_FILE"
say "Building and starting MediFlow (the first build takes 10-20 minutes)"
$COMPOSE up -d --build --remove-orphans

say "Waiting for the services to be ready"
for i in $(seq 1 90); do
  if curl -fsS -o /dev/null http://localhost:8080/healthz && curl -fsS -o /dev/null http://localhost:8081/ \
     && curl -fsS -o /dev/null http://localhost:8082/up && curl -fsS -o /dev/null http://localhost:8080/api/health; then
    READY=1; break
  fi
  sleep 5
done
if [ "${READY:-0}" != 1 ]; then
  echo "Some services aren't answering yet. Check with: $COMPOSE ps   and   $COMPOSE logs --tail=50"
  exit 1
fi

# ---------------------------------------------------------------- 6. Demo passwords (first run only)
CREDS=deploy/.credentials
if [ "$FIRST_RUN" = 1 ] || [ ! -f "$CREDS" ]; then
  say "Giving the demo accounts random passwords"
  umask 077
  : > "$CREDS"
  for user in admin manager doctor nurse; do
    pw="$(rand 6)A!"
    $COMPOSE exec -T api python manage.py shell -c \
      "from apps.accounts.models import User; u=User.objects.filter(username='$user').first(); u and (u.set_password('$pw'), u.save())" >/dev/null
    echo "$user  $pw" >> "$CREDS"
  done
fi

cat <<EOF

MediFlow is running.

  Staff app          http://$PUBLIC_HOST:8080
  Student dashboard  http://$PUBLIC_HOST:8081
  Admin console      http://$PUBLIC_HOST:8082

  Sign-in accounts (also saved in $DIR/$CREDS):
$(sed 's/^/    /' "$CREDS")

  Update later:  run this script again.
  Logs:          cd $DIR && $COMPOSE logs -f --tail=100
  Stop:          cd $DIR && $COMPOSE down        (data is kept)

This uses plain HTTP on the server's IP: fine for a demo with made-up data.
Before real patient data: add a domain and HTTPS (see deploy/README.md).
EOF
