"""TOTP-based multi-factor authentication using the Time-based One-Time Password algorithm.

TOTP generates a short-lived numeric code from a shared secret and the current
UTC time, allowing the server to verify a code without storing the user's
password. The implementation supports Google Authenticator and Authy by using
standard RFC 6238-compatible time-based codes.

Example:
    >>> service = MFAService()
    >>> secret = service.generate_secret()
    >>> uri = service.get_provisioning_uri(secret, "student@futa.edu.ng")
    >>> isinstance(uri, str)
    True
"""

from __future__ import annotations

import base64
import io
import hashlib
from typing import Any, Final

import pyotp
import qrcode

from security.encryption.field_encryption import encrypt_field, decrypt_field
from security.utils.token_utils import generate_backup_codes


class MFARequired(Exception):
    """Raised when MFA is required but not satisfied."""


class MFAInvalid(Exception):
    """Raised when a provided MFA code is invalid or expired."""


class MFAService:
    """Manage TOTP-based MFA setup, verification, and backup-code handling."""

    _WINDOW: Final[int] = 1
    _OTP_DIGITS: Final[int] = 6
    _BACKUP_CODE_LENGTH: Final[int] = 8

    def generate_secret(self) -> str:
        """Generate a fresh base32 TOTP secret for a user.

        Returns:
            A base32-encoded shared secret compatible with authenticator apps.
        """
        return pyotp.random_base32()

    def get_provisioning_uri(self, secret: str, user_email: str, issuer: str = "FUTA Health") -> str:
        """Generate an otpauth URI for app enrollment.

        Args:
            secret: Base32 TOTP secret.
            user_email: User email used in the provisioning URI.
            issuer: Display name for the authenticator app.

        Returns:
            A provisioning URI for QR code generation.

        Raises:
            MFAInvalid: If the secret or email is empty.
        """
        if not secret or not isinstance(secret, str):
            raise MFAInvalid("Secret must be a non-empty string.")
        if not user_email or not isinstance(user_email, str):
            raise MFAInvalid("User email must be a non-empty string.")

        return pyotp.totp.TOTP(secret).provisioning_uri(
            name=user_email,
            issuer_name=issuer,
        )

    def generate_qr_code(self, provisioning_uri: str) -> bytes:
        """Generate a PNG QR code image for the provisioning URI.

        Args:
            provisioning_uri: The otpauth URI generated by ``get_provisioning_uri``.

        Returns:
            PNG-encoded QR code bytes.

        Raises:
            MFAInvalid: If the provisioning URI is empty.
        """
        if not provisioning_uri or not isinstance(provisioning_uri, str):
            raise MFAInvalid("Provisioning URI must be a non-empty string.")

        qr = qrcode.QRCode(version=1, box_size=10, border=4)
        qr.add_data(provisioning_uri)
        qr.make(fit=True)

        image = qr.make_image(fill_color="black", back_color="white")
        buffer = io.BytesIO()
        image.save(buffer, format="PNG")
        return buffer.getvalue()

    def verify_code(self, secret: str, code: str) -> bool:
        """Verify a TOTP code with a ±1 window tolerance for clock drift.

        Args:
            secret: Base32 TOTP secret.
            code: 6-digit authenticator code.

        Returns:
            ``True`` when the code matches within the allowed drift window.
        """
        if not secret or not isinstance(secret, str):
            raise MFAInvalid("Secret must be a non-empty string.")
        if not code or not isinstance(code, str):
            raise MFAInvalid("Code must be a non-empty string.")

        try:
            token = pyotp.TOTP(secret)
            return token.verify(code, valid_window=self._WINDOW)
        except Exception as exc:  # pragma: no cover - defensive guard
            raise MFAInvalid("Unable to validate MFA code.") from exc

    def generate_backup_codes(self, count: int = 10) -> list[str]:
        """Generate one-time-use backup codes for MFA recovery.

        Args:
            count: Number of codes to generate.

        Returns:
            A list of unique 8-character uppercase alphanumeric backup codes.
        """
        if not isinstance(count, int) or count < 1:
            raise MFAInvalid("Backup code count must be a positive integer.")

        codes = generate_backup_codes(count)
        return [code.upper() for code in codes]

    def verify_backup_code(self, user: Any, code: str) -> bool:
        """Verify a single-use backup code against the user's stored hash.

        Backup codes are stored as hashed values, not plaintext, to reduce the
        impact of a database compromise. Each successful use invalidates the code.

        Args:
            user: User object exposing ``backup_codes`` or equivalent stored values.
            code: Backup code candidate submitted by the user.

        Returns:
            ``True`` when the code matches and is still valid; otherwise ``False``.
        """
        if user is None:
            return False
        if not code or not isinstance(code, str):
            return False

        normalized_code = code.strip().upper()
        backup_codes = getattr(user, "backup_codes", []) or []

        for entry in backup_codes:
            if not isinstance(entry, dict):
                continue
            stored_code = entry.get("code")
            if not stored_code:
                continue
            if hashlib.sha256(normalized_code.encode("utf-8")).hexdigest() == stored_code:
                if entry.get("used", False):
                    return False
                entry["used"] = True
                return True

        return False

    def store_secret(self, user: Any, secret: str) -> None:
        """Encrypt and store a TOTP secret at rest for the user."""
        if user is None:
            raise MFAInvalid("User is required to store MFA secret.")
        encrypted_secret = encrypt_field(secret)
        user.mfa_secret = encrypted_secret
        if hasattr(user, "save"):
            user.save()

    def get_secret(self, user: Any) -> str:
        """Retrieve and decrypt the stored TOTP secret for the user."""
        if user is None:
            raise MFAInvalid("User is required to fetch MFA secret.")
        encrypted_secret = getattr(user, "mfa_secret", None)
        if not encrypted_secret:
            raise MFAInvalid("User does not have an MFA secret configured.")
        return decrypt_field(encrypted_secret)


